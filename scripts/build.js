#!/usr/bin/env node
// Builds the two products from one shared core (src/core.js):
//   web/index.html  - the browser app (single self-contained file)
//   lib/core.cjs    - the same core wrapped as a CommonJS factory for the CLI
'use strict';
const fs = require('fs');
const path = require('path');
const vm = require('vm');

const root = path.resolve(__dirname, '..');
const read = p => fs.readFileSync(path.join(root, p), 'utf8');
const core = read('src/core.js');

function check(code, file) {
  try { new vm.Script(code, { filename: file }); }
  catch (err) { console.error(`syntax error in ${file}: ${err.message}`); process.exit(1); }
}

// ---- web app ----
const webParts = ['src/web/platform-web.js', 'src/core.js', 'src/web/editor.js', 'src/web/ui.js', 'src/web/io.js'];
const js = "(() => {\n'use strict';\n" + webParts.map(read).join('\n') + '\n})();\n';
if (/<\/script/i.test(js)) { console.error('script terminator inside JS'); process.exit(1); }
check(js, 'web-app.js');
const html = read('src/web/shell.html').replace('/*CSS*/', () => read('src/web/style.css')).replace('/*JS*/', () => js);
fs.mkdirSync(path.join(root, 'web'), { recursive: true });
fs.writeFileSync(path.join(root, 'web/index.html'), html);

// ---- CLI core ----
const names = new Set();
for (const m of core.matchAll(/^(?:async\s+)?(?:function\*?|const|let)\s+([A-Za-z_$][\w$]*)/gm)) names.add(m[1]);
names.delete('project');
const exportsList = [...names].sort().join(', ');
const cjs = `// GENERATED by scripts/build.js from src/core.js - do not edit by hand.
'use strict';
module.exports = function createCore(PLATFORM) {
const Path2D = PLATFORM.Path2D;
${core}
return {
  get project() { return project; },
  set project(p) { project = p; },
  ${exportsList}
};
};
`;
check(cjs, 'lib/core.cjs');
fs.writeFileSync(path.join(root, 'lib/core.cjs'), cjs);
console.log(`built web/index.html (${(html.length / 1024).toFixed(0)} KB) and lib/core.cjs (${names.size} exports)`);
